def svg_line(series: list, width=560, height=120, color="#2563eb") -> str:
    """Tiny inline-SVG line chart; None values break the line."""
    pts = [(i, v) for i, v in enumerate(series) if v is not None]
    if not pts:
        return "<svg></svg>"
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    x0, x1 = min(xs), max(xs)
    y0, y1 = min(ys), max(ys)
    span_x = max(x1 - x0, 1)
    span_y = max(y1 - y0, 1)
    pad = 8

    def px(x):
        return pad + (x - x0) / span_x * (width - 2 * pad)

    def py(y):
        return height - pad - (y - y0) / span_y * (height - 2 * pad)

    path = " ".join(f"{'M' if i == 0 else 'L'}{px(x):.1f},{py(y):.1f}"
                    for i, (x, y) in enumerate(pts))
    dots = "".join(f'<circle cx="{px(x):.1f}" cy="{py(y):.1f}" r="3" fill="{color}"/>'
                   for x, y in pts)
    return (f'<svg viewBox="0 0 {width} {height}" role="img">'
            f'<path d="{path}" fill="none" stroke="{color}" stroke-width="2"/>'
            f"{dots}</svg>")


def render_dashboard(snaps: list[dict]) -> str:
    dates = [s["generated"] for s in snaps]
    latest = snaps[-1]
    latest_rep = latest["reports"][-1]

    def series(getter):
        return [getter(s) for s in snaps]

    cards = [
        ("Risk score", series(lambda s: s["risk_score"]), "#dc2626"),
        ("Open findings", series(lambda s: s["reports"][-1]["open_total"]), "#ea580c"),
        ("CRITICAL + HIGH open",
         series(lambda s: s["reports"][-1]["open_by_severity"].get("CRITICAL", 0)
                + s["reports"][-1]["open_by_severity"].get("HIGH", 0)), "#b91c1c"),
        ("Hotspot lines (total)",
         series(lambda s: sum(v for v in s["hotspots"].values() if v)), "#2563eb"),
        ("Hygiene counters (total)",
         series(lambda s: sum(s["hygiene"].values())), "#7c3aed"),
        ("Test files (all areas)",
         series(lambda s: sum(s["areas"].get(a, {}).get("test_files", 0)
                              for a in ("api", "frontend", "android"))), "#059669"),
    ]

    tiles = "".join(
        f'<div class="card"><h2>{html.escape(title)}</h2>'
        f'<div class="num">{fmt(vals[-1])}</div>{svg_line(vals, color=color)}'
        f"</div>"
        for title, vals, color in cards
    )

    sev_rows = "".join(
        f"<tr><td>{sev.title()}</td>"
        + "".join(f"<td>{fmt(s['reports'][-1]['open_by_severity'].get(sev))}</td>"
                  for s in snaps)
        + "</tr>"
        for sev in SEVERITIES
    )
    date_heads = "".join(f"<th>{d}</th>" for d in dates)

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Audit Trend — Vox Quieta</title>
<style>
  :root {{ color-scheme: light dark; font-family: system-ui, sans-serif; }}
  body {{ margin: 2rem auto; max-width: 72rem; padding: 0 1rem; }}
  h1 {{ margin-bottom: 0.2rem; }}
  .sub {{ color: #6b7280; margin-bottom: 2rem; }}
  .grid {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(320px, 1fr)); gap: 1rem; }}
  .card {{ border: 1px solid #d1d5db55; border-radius: 10px; padding: 1rem; }}
  .card h2 {{ font-size: 0.9rem; margin: 0 0 0.3rem; color: #6b7280; font-weight: 600; }}
  .card .num {{ font-size: 1.8rem; font-weight: 700; margin-bottom: 0.4rem; }}
  svg {{ width: 100%; height: auto; }}
  table {{ border-collapse: collapse; margin-top: 2rem; width: 100%; }}
  th, td {{ border: 1px solid #d1d5db55; padding: 0.4rem 0.7rem; text-align: right; }}
  th:first-child, td:first-child {{ text-align: left; }}
  .foot {{ margin-top: 2rem; color: #6b7280; font-size: 0.85rem; }}
</style>
</head>
<body>
<h1>Audit Trend</h1>
<p class="sub">Latest snapshot {html.escape(latest["generated"])}
 (commit <code>{html.escape(latest["commit"])}</code>) ·
 latest audit <strong>{html.escape(latest_rep["month"])}</strong> ·
 {latest_rep["open_total"]} open findings · risk score {latest_rep["risk_score"]}.
 Lower is better everywhere except tests.</p>
<div class="grid">{tiles}</div>
<table>
<thead><tr><th>Open by severity</th>{date_heads}</tr></thead>
<tbody>{sev_rows}</tbody>
</table>
<p class="foot">Generated by <code>make audit-metrics</code>
 (<code>tools/audit-metrics/</code>). Full tables in
 <a href="./report.md">report.md</a>; audit reports in
 <code>docs/audits/</code>.</p>
</body>
</html>
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-root", default=None)
    args = ap.parse_args()

    repo = Path(args.repo_root) if args.repo_root else Path(__file__).resolve().parents[2]
    out_dir = repo / "docs" / "audits" / "metrics"
    snaps = load_history(out_dir / "history")
    if not snaps:
        raise SystemExit("no snapshots — run tools/audit-metrics/analyze.py first")

    (out_dir / "report.md").write_text(render_report(snaps), encoding="utf-8")
    (out_dir / "index.html").write_text(render_dashboard(snaps), encoding="utf-8")
    print(f"wrote {out_dir / 'report.md'} and {out_dir / 'index.html'}")


if __name__ == "__main__":
    main()
