#!/usr/bin/env python3
"""Render docs/audits/metrics/report.md and index.html from the dated
snapshots produced by analyze.py. Stdlib only — no dependencies.

The report is tables (newest snapshot last, so columns read left→right in
time); the dashboard is a single self-contained HTML file with inline-SVG
trend lines, same spirit as tools/repo-metrics/.

Usage: python3 tools/audit-metrics/render.py [--repo-root PATH]
"""

from __future__ import annotations

import argparse
import html
import json
from pathlib import Path

MAX_COLUMNS = 8  # most recent snapshots shown in report tables

SEVERITIES = ["CRITICAL", "HIGH", "MEDIUM", "LOW"]

CATEGORY_LABELS = {
    "architectural_debt": "Architectural debt",
    "edge_case_failures": "Edge-case failures",
    "scalability_bottlenecks": "Scalability bottlenecks",
    "doc_test_gaps": "Doc & test gaps",
    "operational_security": "Operational / security",
}

HYGIENE_LABELS = {
    "api_sync_httpx_client": "Sync httpx.Client in api/ (S1)",
    "api_broad_except": "Broad excepts in api/",
    "api_noqa": "# noqa in api/",
    "frontend_eslint_disable": "eslint-disable in frontend/",
    "frontend_ts_suppress": "@ts-ignore/expect-error",
    "android_run_blocking": "runBlocking on Android (S6)",
    "android_suppress": "@Suppress on Android",
    "todo_fixme_hack": "TODO/FIXME/HACK in code",
    "cruft_files": "Tracked cruft files (.old/.backup)",
    "compose_variants": "docker-compose variants",
}


def load_history(history_dir: Path) -> list[dict]:
    snaps = []
    for p in sorted(history_dir.glob("*.json")):
        snaps.append(json.loads(p.read_text(encoding="utf-8")))
    return snaps


def fmt(n) -> str:
    return "—" if n is None else str(n)


def delta(cur, prev) -> str:
    """Direction marker vs the previous snapshot. Lower is better for every
    metric this tool tracks, so ▲ (growth) is the bad direction."""
    if cur is None or prev is None or cur == prev:
        return ""
    return f" {'▲' if cur > prev else '▼'}{abs(cur - prev)}"


def table(rows: list[list[str]]) -> str:
    header, *body = rows
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in body]
    return "\n".join(out)


def metric_rows(snaps: list[dict], label: str, getter) -> list[str]:
    """One table row: label, value per snapshot, delta on the newest."""
    vals = [getter(s) for s in snaps]
    cells = [fmt(v) for v in vals]
    if len(vals) >= 2:
        cells[-1] += delta(vals[-1], vals[-2])
    return [label, *cells]


def render_report(snaps: list[dict]) -> str:
    shown = snaps[-MAX_COLUMNS:]
    dates = [s["generated"] for s in shown]
    latest = shown[-1]
    latest_rep = latest["reports"][-1]

    lines = [
        "# Audit Trend Report",
        "",
        "*Generated by `make audit-metrics` (`tools/audit-metrics/`). Do not edit by hand.*",
        f"*Latest snapshot: **{latest['generated']}** (commit `{latest['commit']}`),"
        f" latest audit: **{latest_rep['month']}**"
        f" ({latest_rep['open_total']} open findings, risk score {latest_rep['risk_score']}).*",
        "",
        "Lower is better for every number on this page;"
        " ▲ marks growth since the previous snapshot, ▼ shrinkage.",
        "",
        "## Risk score",
        "",
        "Weighted open findings of the most recent audit at each snapshot"
        " (CRITICAL=10, HIGH=5, MEDIUM=2, LOW=1).",
        "",
        table([
            ["Metric", *dates],
            metric_rows(shown, "Risk score", lambda s: s["risk_score"]),
            metric_rows(shown, "Open findings", lambda s: s["reports"][-1]["open_total"]),
            *[metric_rows(shown, sev.title(),
                          lambda s, v=sev: s["reports"][-1]["open_by_severity"].get(v))
              for sev in SEVERITIES],
            metric_rows(shown, "Resolved (cumulative)",
                        lambda s: sum(len(r["resolved_ids"]) for r in s["reports"])),
        ]),
        "",
        "## Open findings by category",
        "",
        table([
            ["Category", *dates],
            *[metric_rows(shown, label,
                          lambda s, k=key: s["reports"][-1]["open_by_category"].get(k))
              for key, label in CATEGORY_LABELS.items()],
        ]),
        "",
        "## Hotspot watch (lines)",
        "",
        "Files flagged by the audits as monoliths or hand-synchronized copies."
        " The goal is for these rows to shrink or disappear (— = file deleted).",
        "",
        table([
            ["File", *dates],
            *[metric_rows(shown, f"`{path.rsplit('/', 1)[-1]}`",
                          lambda s, p=path: s["hotspots"].get(p))
              for path in latest["hotspots"]],
        ]),
        "",
        "## Hygiene counters",
        "",
        table([
            ["Counter", *dates],
            *[metric_rows(shown, label,
                          lambda s, k=key: s["hygiene"].get(k))
              for key, label in HYGIENE_LABELS.items()
              if key in latest["hygiene"]],
        ]),
        "",
        "## Test surface",
        "",
        "The one section where growth is good (shown without direction markers).",
        "",
        table([
            ["Metric", *dates],
            *[[f"{area} test files",
               *[fmt(s["areas"].get(area, {}).get("test_files")) for s in shown]]
              for area in ("api", "frontend", "android")],
            ["frontend e2e specs",
             *[fmt(s["areas"].get("frontend_e2e_specs")) for s in shown]],
        ]),
        "",
        "## How to refresh",
        "",
        "```sh",
        "make audit-metrics",
        "```",
        "",
        "Snapshots accumulate under `docs/audits/metrics/history/`;"
        " run it after each `/risk-audit` and let the monthly workflow"
        " (`.github/workflows/audit-metrics.yml`) fill the gaps between audits.",
        "",
    ]
    return "\n".join(lines)


